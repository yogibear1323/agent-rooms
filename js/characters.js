function pad32(rows) {
  return rows.map((row) => row.slice(0, 32).padEnd(32, "."));
}

function runsToRects(rows, className) {
  const parts = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      const fill = PALETTE[ch];
      if (!fill) {
        x += 1;
        continue;
      }
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) w += 1;
      parts.push(
        `<rect class="${className}" x="${x}" y="${y}" width="${w}" height="1" fill="${fill}"/>`,
      );
      x += w;
    }
  });
  return parts.join("");
}

