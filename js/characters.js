export const KNOWN_CHARACTERS = Object.keys(CHAR_LABELS);

export function syncCharacter(el, { kind, character, state, size = 256 } = {}) {
  if (!el) return;
  const raw = (character || kind || "scout").toString().toLowerCase();
  const aliases = { finance: "accountant", content: "creator", merch: "designer", "lead-followup": "concierge", lead_followup: "concierge" };
  let k = CHAR_LABELS[raw] ? raw : (aliases[raw] || "");
  if (!k) {
    k = ["designer", "accountant", "concierge", "recruiter", "creator", "scout"].find((key) => raw.includes(key)) || "";
    if (!k && (raw.includes("camera") || raw.includes("speech bubble"))) k = "creator";
    if (!k) k = "generic";
  }
  const st = STATES.has(state) ? state : "idle";
  const label = CHAR_LABELS[k] || "Agent";
  let svg = el.querySelector("svg.char");
  if (!svg || svg.getAttribute("data-kind") !== k) {
    el.innerHTML = renderSvg(k, st, size);
  } else {
    svg.setAttribute("data-state", st);
    svg.setAttribute("aria-label", `${label} character, ${st}`);
  }
}

